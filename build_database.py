"""Build dol_visas.duckdb from DOL OFLC disclosure workbooks.

Pipeline: sources.yaml (file inventory) -> data/raw/*.xlsx (cached by
download step) -> crosswalk_lca.csv / crosswalk_perm.csv (per-era column
mappings generated by build_crosswalk.py) -> typed canonical tables
`lca` and `perm` -> _metadata/_columns/DICTIONARY.md -> validation.

Every disclosure row is kept (no dedup): amended/re-decided cases appear
once per disclosure file; `is_latest` flags the most recent disclosure per
case number within each program.
"""
import argparse
import json
import os
import csv
import re
import sys
import time
from collections import defaultdict
from datetime import datetime
from pathlib import Path

import duckdb
import requests
import yaml

# Source columns that no crosswalk era maps (filled by build_table).
UNMAPPED_COLUMNS: list[tuple[str, list[str]]] = []
ALLOW_UNMAPPED = False
WRITE_KNOWN_UNMAPPED = False

sys.stdout.reconfigure(encoding="utf-8", errors="replace")

DEFAULT_OUTPUT = "dol_visas.duckdb"
RAW_DIR = Path("data/raw")

DATE_COLS = {
    "received_date", "decision_date", "original_cert_date", "begin_date",
    "end_date", "orig_file_date", "pw_determination_date",
    "pw_expiration_date",
}
DOUBLE_COLS = {
    "prevailing_wage", "wage_rate_of_pay_from", "wage_rate_of_pay_to",
    "wage_offer_from", "wage_offer_to", "pw_wage",
}
INT_COLS = {
    "total_worker_positions", "new_employment", "continued_employment",
    "change_previous_employment", "new_concurrent_employment",
    "change_employer", "amended_petition", "employer_num_employees",
    "employer_year_established", "required_training_months",
    "required_experience_months", "pw_wage_source_year", "pw_oes_year",
    "pw_other_year", "foreign_worker_yrs_ed_comp",
    "total_worksite_locations", "worksite_workers",
}

TABLE_DESCRIPTIONS = {
    "lca": "H-1B/H-1B1/E-3 Labor Condition Applications, one row per "
           "application per disclosure file, FY2015-present",
    "perm": "PERM permanent labor certification applications, one row per "
            "application per disclosure file, FY2015-present",
}


def era_of_file(f: str) -> str:
    if f.startswith(("H-1B_Disclosure_Data_FY15", "H-1B_Disclosure_Data_FY16")):
        return "lca_2015"
    if f.startswith(("H-1B_Disclosure_Data_FY17", "H-1B_Disclosure_Data_FY2018")):
        return "lca_2017"
    if f.startswith("H-1B_Disclosure_Data_FY2019"):
        return "lca_2019"
    if f.startswith("LCA_Disclosure"):
        return "lca_2020"
    if f.startswith("PERM_Disclosure_Data_New_Form"):
        return "perm_2024"
    if f.startswith(("PERM_Disclosure_Data_FY2025", "PERM_Disclosure_Data_FY2026")):
        return "perm_2024"
    if re.match(r"PERM_Disclosure_Data_FY202[0-4]", f):
        return "perm_2020"
    return "perm_2015"


def fy_quarter(f: str) -> tuple[int, str | None]:
    m = re.search(r"FY(\d{4}|\d{2})", f)
    fy = int(m.group(1))
    fy = fy + 2000 if fy < 100 else fy
    qm = re.search(r"_Q([1-4])", f)
    # Pre-FY2020 releases are end-of-year files even when named _Q4.
    quarter = f"Q{qm.group(1)}" if qm and fy >= 2020 else None
    return fy, quarter


def load_crosswalk(path: str) -> dict[str, dict[str, str]]:
    """era -> {source_column: canonical_column} (drops excluded)."""
    cw = defaultdict(dict)
    for r in csv.DictReader(open(path)):
        if r["kind"] != "drop":
            cw[r["era"]][r["source_column"]] = r["canonical_column"]
    return cw


def canonical_type(col: str) -> str:
    if col in DATE_COLS:
        return "DATE"
    if col in DOUBLE_COLS:
        return "DOUBLE"
    if col in INT_COLS:
        return "INTEGER"
    return "VARCHAR"


def cast_expr(source_sql: str, canonical: str) -> str:
    """Typed cast of an all_varchar source expression."""
    if canonical in DATE_COLS:
        return (f"COALESCE(TRY_CAST({source_sql} AS DATE), "
                f"TRY_STRPTIME({source_sql}, '%m/%d/%Y')::DATE)")
    if canonical in DOUBLE_COLS:
        cleaned = (f"NULLIF(TRIM(REPLACE(REPLACE({source_sql}, '$', ''), "
                   f"',', '')), '')")
        return f"TRY_CAST({cleaned} AS DOUBLE)"
    if canonical in INT_COLS:
        return f"TRY_CAST(TRY_CAST({source_sql} AS DOUBLE) AS INTEGER)"
    # Older workbooks write the literal string 'NULL' for missing values.
    return f"NULLIF(NULLIF(TRIM({source_sql}), ''), 'NULL')"


def download_file(url: str, dest: Path) -> bool:
    if dest.exists() and dest.stat().st_size > 0:
        return True
    dest.parent.mkdir(parents=True, exist_ok=True)
    for attempt in range(3):
        try:
            r = requests.get(url, stream=True, timeout=120)
            r.raise_for_status()
            total = int(r.headers.get("content-length", 0))
            received = 0
            with open(dest, "wb") as fh:
                for chunk in r.iter_content(1024 * 256):
                    fh.write(chunk)
                    received += len(chunk)
            if total and received != total:
                raise IOError(f"truncated: {received}/{total}")
            return True
        except Exception as e:
            print(f"    WARNING: download attempt {attempt + 1}/3 {url}: {e}")
            dest.unlink(missing_ok=True)
    return False


def download_all(sources: dict) -> list[tuple[str, Path]]:
    base = sources["base_url"]
    files = []
    for program in ("lca", "perm"):
        for fy, names in sources[program].items():
            for name in names:
                url = name if name.startswith("http") else f"{base}/{name}"
                # Local name: strip URL path, keep canonical filename (fixes
                # DOL's FY2026 'Dislclosure' typo to keep era detection sane)
                local = url.rsplit("/", 1)[-1].replace("Dislclosure", "Disclosure")
                dest = RAW_DIR / local
                if not download_file(url, dest):
                    raise SystemExit(f"FATAL: could not download {url}")
                files.append((program, dest))
    return files


def build_table(con, program: str, files: list[Path], crosswalk) -> int:
    canon_cols = sorted({c for era in crosswalk.values() for c in era.values()})
    col_defs = ", ".join(f'"{c}" {canonical_type(c)}' for c in canon_cols)
    con.execute(f"""
        CREATE OR REPLACE TABLE {program} (
            {col_defs},
            fiscal_year INTEGER,
            quarter VARCHAR,
            source_file VARCHAR,
            is_latest BOOLEAN
        )
    """)

    total = 0
    for path in sorted(files):
        fname = path.name
        era = era_of_file(fname)
        fy, quarter = fy_quarter(fname)
        mapping = crosswalk[era]
        # source header set for THIS file
        cols_here = [d[0] for d in con.execute(
            f"SELECT * FROM read_xlsx('{path}', all_varchar=true) LIMIT 0"
        ).description]
        canon_from_source = {}
        unmapped = []
        for src in cols_here:
            if src in mapping:
                canon_from_source[mapping[src]] = f'"{src}"'
            else:
                unmapped.append(src)
        if unmapped:
            # A new DOL column that is not in the crosswalk would otherwise be
            # dropped silently. Record it so run_validation() can fail the build.
            UNMAPPED_COLUMNS.append((fname, unmapped))
            print(f"    WARNING: {fname}: {len(unmapped)} source column(s) not in "
                  f"crosswalk era '{era}' and will be DROPPED: {unmapped[:8]}"
                  f"{'...' if len(unmapped) > 8 else ''}")

        exprs = []
        for c in canon_cols:
            src_sql = canon_from_source.get(c)
            # FY2015-16 LCA publishes one WAGE_RATE_OF_PAY value that may be
            # a "from - to" range: split it into the canonical pair.
            if era == "lca_2015" and c == "wage_rate_of_pay_from" and src_sql:
                src_sql = f"split_part({src_sql}, '-', 1)"
            if (era == "lca_2015" and c == "wage_rate_of_pay_to"
                    and src_sql is None and "WAGE_RATE_OF_PAY" in cols_here):
                src_sql = "split_part(\"WAGE_RATE_OF_PAY\", '-', 2)"
            if src_sql:
                exprs.append(f'{cast_expr(src_sql, c)} AS "{c}"')
            else:
                exprs.append(f'NULL AS "{c}"')

        select = ", ".join(exprs)
        con.execute(f"""
            INSERT INTO {program}
            SELECT {select},
                   {fy} AS fiscal_year,
                   {"'" + quarter + "'" if quarter else "NULL"} AS quarter,
                   '{fname}' AS source_file,
                   NULL AS is_latest
            FROM read_xlsx('{path}', all_varchar=true)
        """)
        n = con.execute(
            f"SELECT COUNT(*) FROM {program} WHERE source_file = '{fname}'"
        ).fetchone()[0]
        total += n
        print(f"  {fname}: {n:,} rows", flush=True)

    # is_latest: latest disclosure per case_number within the program
    con.execute(f"""
        CREATE OR REPLACE TABLE {program} AS
        SELECT * EXCLUDE (is_latest),
               ROW_NUMBER() OVER (
                   PARTITION BY case_number
                   ORDER BY decision_date DESC NULLS LAST,
                            received_date DESC NULLS LAST,
                            fiscal_year DESC,
                            quarter DESC NULLS LAST
               ) = 1 AS is_latest
        FROM {program}
    """)
    return total


def normalize_values(con):
    """Unify categorical values that differ only by era formatting.

    DOL changed casing and punctuation across file generations
    ('Certified' vs 'CERTIFIED', 'Certified - Withdrawn' vs
    'CERTIFIED-WITHDRAWN', 'Level IV' vs 'IV', 'Yes' vs 'Y'). Values are
    normalized to one domain per column so GROUP BY and filters behave.
    """
    for tbl in ("lca", "perm"):
        con.execute(f"""
            UPDATE {tbl}
            SET case_status = UPPER(REPLACE(case_status, ' - ', '-'))
        """)
    con.execute("""
        UPDATE lca SET
            pw_wage_level = NULLIF(UPPER(REPLACE(pw_wage_level, 'Level ', '')), 'N/A'),
            h_1b_dependent = CASE
                WHEN h_1b_dependent IN ('Y', 'Yes') THEN 'Y'
                WHEN h_1b_dependent IN ('N', 'No') THEN 'N' END,
            willful_violator = CASE
                WHEN willful_violator IN ('Y', 'Yes') THEN 'Y'
                WHEN willful_violator IN ('N', 'No') THEN 'N' END,
            visa_class = NULLIF(visa_class, 'Select Visa Classification')
    """)
    con.execute("UPDATE perm SET pw_level = NULLIF(REPLACE(pw_level, 'Level ', ''), 'N/A')")
    print("  normalized categorical domains")


