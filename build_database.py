def build_metadata(con, built: dict[str, int]):
    con.execute("""
        CREATE OR REPLACE TABLE _metadata (
            table_name VARCHAR, description VARCHAR, row_count BIGINT,
            column_count INTEGER, data_sources VARCHAR, date_range VARCHAR,
            built_at TIMESTAMP
        )
    """)
    now = datetime.now().isoformat()
    for tbl in built:
        rc = con.execute(f"SELECT COUNT(*) FROM {tbl}").fetchone()[0]
        cc = len(con.execute(f"SELECT * FROM {tbl} LIMIT 0").description)
        fy = con.execute(
            f"SELECT MIN(fiscal_year), MAX(fiscal_year) FROM {tbl}"
        ).fetchone()
        con.execute(
            "INSERT INTO _metadata VALUES (?, ?, ?, ?, ?, ?, ?)",
            [tbl, TABLE_DESCRIPTIONS[tbl], rc, cc,
             "DOL OFLC disclosure files (dol.gov/agencies/eta/foreign-labor/performance)",
             f"FY{fy[0]} to FY{fy[1]}", now],
        )


def build_columns_table(con):
    con.execute("DROP TABLE IF EXISTS _columns")
    con.execute("""
        CREATE TABLE _columns AS
        SELECT c.table_name, c.column_name, c.data_type,
               CAST(NULL AS DOUBLE) AS null_pct,
               CAST(NULL AS VARCHAR) AS example_value
        FROM information_schema.columns c
        WHERE c.table_name IN ('lca', 'perm')
        ORDER BY c.table_name, c.ordinal_position
    """)
    rows = con.execute(
        "SELECT table_name, column_name FROM _columns"
    ).fetchall()
    for tbl, col in rows:
        stats = con.execute(f'''
            SELECT ROUND(100.0 * COUNT(*) FILTER (WHERE "{col}" IS NULL)
                   / COUNT(*), 1),
                   MIN(CAST("{col}" AS VARCHAR)) FILTER (WHERE "{col}" IS NOT NULL)
            FROM {tbl}
        ''').fetchone()
        con.execute(
            "UPDATE _columns SET null_pct = ?, example_value = ? "
            "WHERE table_name = ? AND column_name = ?",
            [stats[0], (stats[1] or "")[:80], tbl, col],
        )


def export_dictionary(con, out: Path):
    lines = [
        "# dol-visas Data Dictionary",
        "",
        "Built from DOL OFLC quarterly disclosure files "
        "(https://www.dol.gov/agencies/eta/foreign-labor/performance).",
        "Column availability varies by fiscal-year era; see crosswalk_lca.csv "
        "and crosswalk_perm.csv in the build repo for the exact per-era "
        "source-column mappings and every documented drop.",
        "",
    ]
    for tbl in ("lca", "perm"):
        meta = con.execute(
            "SELECT description, row_count FROM _metadata WHERE table_name = ?",
            [tbl],
        ).fetchone()
        lines += [f"## {tbl}", "", f"{meta[0]}. {meta[1]:,} rows.", "",
                  "| Column | Type | Null % | Example |",
                  "|--------|------|--------|---------|"]
        for col, dt, np, ex in con.execute(
            "SELECT column_name, data_type, null_pct, example_value "
            "FROM _columns WHERE table_name = ? ", [tbl]
        ).fetchall():
            ex = (ex or "").replace("|", "/")
            lines.append(f"| `{col}` | {dt} | {np}% | {ex} |")
        lines.append("")
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"  Exported {out}")


def run_validation(con, db_path: Path):
    print("\n" + "=" * 60 + "\nVALIDATION\n" + "=" * 60)
    for tbl in ("lca", "perm"):
        print(f"\n  {tbl} rows by fiscal year:")
        for fy, n in con.execute(
            f"SELECT fiscal_year, COUNT(*) FROM {tbl} GROUP BY 1 ORDER BY 1"
        ).fetchall():
            print(f"    FY{fy}: {n:,}")
    print("\n  LCA case status distribution (all years):")
    for s, n in con.execute(
        "SELECT case_status, COUNT(*) FROM lca GROUP BY 1 ORDER BY 2 DESC LIMIT 6"
    ).fetchall():
        print(f"    {s}: {n:,}")
    print("\n  Top LCA employers by certified applications, FY2025:")
    for e, n in con.execute("""
        SELECT employer_name, COUNT(*) FROM lca
        WHERE fiscal_year = 2025 AND case_status ILIKE 'Certified%'
        GROUP BY 1 ORDER BY 2 DESC LIMIT 10
    """).fetchall():
        print(f"    {e}: {n:,}")
    print("\n  LCA median annual wage_rate_of_pay_from by top SOC, FY2025:")
    for s, m, n in con.execute("""
        SELECT soc_title, MEDIAN(wage_rate_of_pay_from), COUNT(*)
        FROM lca WHERE fiscal_year = 2025 AND wage_unit_of_pay ILIKE 'Year%'
        GROUP BY 1 ORDER BY 3 DESC LIMIT 5
    """).fetchall():
        print(f"    {s}: ${m:,.0f} (n={n:,})")
    print("\n  PERM case status distribution:")
    for s, n in con.execute(
        "SELECT case_status, COUNT(*) FROM perm GROUP BY 1 ORDER BY 2 DESC LIMIT 6"
    ).fetchall():
        print(f"    {s}: {n:,}")
    print("\n  Duplicate case_numbers flagged (is_latest=false rows):")
    for tbl in ("lca", "perm"):
        n = con.execute(
            f"SELECT COUNT(*) FROM {tbl} WHERE NOT is_latest"
        ).fetchone()[0]
        print(f"    {tbl}: {n:,}")
    size_mb = db_path.stat().st_size / 1024 / 1024 if db_path.exists() else 0
    total = con.execute(
        "SELECT SUM(row_count) FROM _metadata"
    ).fetchone()[0]
    print(f"\n  Total rows: {total:,}")

    # ---- Regression guards ----
    print("\n  Audit checks:")
    failures = 0

    def check(name, ok, detail=""):
        nonlocal failures
        print(f"    [{'PASS' if ok else 'FAIL'}] {name}" + (f"  ({detail})" if detail else ""))
        if not ok:
            failures += 1

    # DOL files carry many columns we deliberately do not load (e.g. the
    # WORKSITE_*_2..10 repeats). known_unmapped.json records those per crosswalk
    # era; the build fails only when a file has a NEW unmapped column, which
    # means DOL changed the layout and the crosswalk needs a row.
    known_path = Path("known_unmapped.json")
    known = json.loads(known_path.read_text()) if known_path.exists() else {}
    new_unmapped = []
    for fname, cols in UNMAPPED_COLUMNS:
        era = era_of_file(fname)
        novel = sorted(set(cols) - set(known.get(era, [])))
        if novel:
            new_unmapped.append((fname, era, novel))
    check("no NEW unmapped source columns (vs known_unmapped.json)",
          not new_unmapped or ALLOW_UNMAPPED,
          "; ".join(f"{f} [{e}]: {c[:5]}" for f, e, c in new_unmapped)[:400])
    if new_unmapped:
        print("    To accept these as intentionally dropped, add them to known_unmapped.json "
              "(python build_database.py --write-known-unmapped) or add crosswalk rows.")
    if WRITE_KNOWN_UNMAPPED:
        merged = {k: sorted(set(v)) for k, v in known.items()}
        for fname, cols in UNMAPPED_COLUMNS:
            era = era_of_file(fname)
            merged[era] = sorted(set(merged.get(era, [])) | set(cols))
        known_path.write_text(json.dumps(merged, indent=2) + "\n")
        print(f"    wrote {known_path} ({sum(len(v) for v in merged.values())} columns over {len(merged)} eras)")
    for tbl, fy_min in (("lca", 2015), ("perm", 2015)):
        fys = {r[0] for r in con.execute(f"SELECT DISTINCT fiscal_year FROM {tbl}").fetchall()}
        expected = set(range(fy_min, 2027))
        check(f"{tbl} has every fiscal year {fy_min}-2026", expected <= fys,
              f"missing: {sorted(expected - fys)}" if expected - fys else "complete")
        n_latest = con.execute(f"SELECT COUNT(*) FROM {tbl} WHERE is_latest").fetchone()[0]
        n_case = con.execute(f"SELECT COUNT(DISTINCT case_number) FROM {tbl}").fetchone()[0]
        check(f"{tbl}: one is_latest row per case_number", n_latest == n_case,
              f"{n_latest:,} latest vs {n_case:,} cases")
    print(f"\n  Audit checks: {failures} failure(s)")
    return failures


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--output", type=Path, default=Path(DEFAULT_OUTPUT))
    p.add_argument("--allow-unmapped", action="store_true",
                   help="Do not fail the build when a source file has columns "
                        "missing from the crosswalk (they are dropped)")
    p.add_argument("--write-known-unmapped", action="store_true",
                   help="Record every unmapped source column of this run in "
                        "known_unmapped.json (accept them as intentionally dropped)")
    args = p.parse_args()
    global ALLOW_UNMAPPED, WRITE_KNOWN_UNMAPPED
    ALLOW_UNMAPPED = args.allow_unmapped
    WRITE_KNOWN_UNMAPPED = args.write_known_unmapped

    t0 = time.time()
    sources = yaml.safe_load(open("sources.yaml"))
    print("[1/5] Downloading disclosure files (cached)")
    files = download_all(sources)
    print(f"  {len(files)} files present")

    args.output.unlink(missing_ok=True)
    con = duckdb.connect(str(args.output))
    con.execute("SET preserve_insertion_order = false")
    con.execute(f"SET temp_directory = '{args.output.resolve()}.tmp'")
    # read_xlsx is memory-hungry and the WSL VM is capped at 10 GB; leave
    # headroom. Override with DATAPOND_MEMORY_LIMIT / DATAPOND_THREADS.
    con.execute(f"SET memory_limit = '{os.environ.get('DATAPOND_MEMORY_LIMIT', '5GB')}'")
    con.execute(f"SET threads = {int(os.environ.get('DATAPOND_THREADS', 4))}")

    built = {}
    for program, cw_path in (("lca", "crosswalk_lca.csv"),
                             ("perm", "crosswalk_perm.csv")):
        print(f"\n[{'2' if program == 'lca' else '3'}/5] Loading {program}")
        cw = load_crosswalk(cw_path)
        flist = [d for pr, d in files if pr == program]
        built[program] = build_table(con, program, flist, cw)

    print("\n[4/5] Metadata and dictionary")
    normalize_values(con)
    build_metadata(con, built)
    build_columns_table(con)
    export_dictionary(con, Path("DICTIONARY.md"))

    print("\n[5/5] Validation")
    con.execute("CHECKPOINT")
    failures = run_validation(con, args.output)
    con.close()
    print(f"\nBUILD DONE in {(time.time() - t0) / 60:.1f} min")
    if failures:
        print(f"BUILD FAILED: {failures} audit check(s) failed -- do not publish this file")
        sys.exit(1)


if __name__ == "__main__":
    main()
